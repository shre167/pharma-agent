"""Cited Markdown report generation from selected evidence, in staged per-section calls.

Instead of one monolithic LLM call that receives every evidence chunk plus the
report request, each report section is generated by its own small call that
receives only the evidence relevant to that section; the section calls run in parallel.
Evidence tags [E<i>] keep
the global numbering of `selected` so verification and the evidence manifest
stay consistent.
"""
from __future__ import annotations

import json
import re
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Callable, Optional

from langsmith import traceable

from ..observability import trace_inputs, trace_output
from .prompts import REPORT_SYSTEM_PROMPT

_EVIDENCE_CAP = 6000

_SECTIONS: list[dict] = [
    {"number": 1, "title": "Product & formulation identity", "chunk_types": ("FORMULATION",), "cap": 2500},
    {"number": 2, "title": "Bill of materials", "chunk_types": ("BOM",), "cap": _EVIDENCE_CAP},
    {"number": 3, "title": "Manufacturing process", "chunk_types": ("PROCESS",), "cap": _EVIDENCE_CAP},
    {"number": 4, "title": "Equipment & process parameters", "chunk_types": ("PROCESS",), "cap": _EVIDENCE_CAP},
    {"number": 5, "title": "Quality attributes", "chunk_types": ("BOM", "PROCESS"), "cap": 2500},
]

DISCLAIMER_TEXT = (
    "This is an educational draft produced from handbook evidence for qualified human review. "
    "It is not a validated manufacturing instruction, batch record or regulatory filing, and "
    "must not be used to make, test or release any product."
)

_GAPS_SECTION = {"number": 6, "title": "Evidence gaps & items needing human review"}


def _strip_own_heading(body: str, number: int) -> str:
    """Remove a leading '## N. ...' line so assembly does not duplicate the heading."""
    return re.sub(rf"^#{{1,4}}\s*0*{number}\.\s.*\n?", "", body or "", count=1)


def _evidence_block(index: int, evidence: dict, cap: int) -> str:
    m = evidence["metadata"]
    return (f"[E{index}] {m.get('formulation_name')} | {m.get('chunk_type')} | "
            f"formulation_id={m.get('formulation_id')} | {evidence.get('citation')}\n"
            f"{evidence['text'][:cap]}")


def _routed_evidence(selected: list[dict], chunk_types: Optional[tuple]) -> tuple[list[int], bool]:
    """Positions (1-based, stable) of chunks relevant to a section, plus whether all were used."""
    if chunk_types is None:
        return list(range(1, len(selected) + 1)), True
    indexes = [i for i, e in enumerate(selected, 1)
               if e.get("metadata", {}).get("chunk_type") in chunk_types]
    if not indexes:
        return list(range(1, len(selected) + 1)), True
    return indexes, False


def _header(report_request: str, classification: dict) -> str:
    return (f"REPORT REQUEST:\n{report_request}\n\n"
            f"TITLE: {classification.get('report_title')}\n"
            f"KNOWN EVIDENCE GAPS FROM AGENT: {json.dumps(classification.get('known_evidence_gaps', []))}\n\n")


def _section_rules(number: int, title: str) -> str:
    return (f"TASK: Write ONLY section {number}. {title} of the cited Markdown report.\n"
            f"- Begin with the exact heading '## {number}. {title}'.\n"
            "- Cite every factual statement as [E<i>] [SOURCE: file, PDF page N], using only the "
            "tagged evidence below.\n"
            "- Keep different formulation instances separate.\n"
            "- Do not write the report title, any other section or a conclusion.\n"
            "- Where the evidence does not support a statement, say so in one line instead of "
            "inventing content.\n")


_SECTION_WORKERS = 5

ProgressFn = Optional[Callable[[str, dict], None]]


@traceable(name="wave1_report_generation", run_type="chain",
           process_inputs=trace_inputs, process_outputs=trace_output)
def generate_report(llm_chat: Callable, report_request: str, selected: list[dict],
                    classification: dict, output_file: Path,
                    progress: ProgressFn = None) -> tuple[str, str]:
    """Build a cited Markdown report from selected evidence; returns (report_text, saved_path)."""
    parts: list[str] = [f"# {classification.get('report_title')}\n"]
    coverage: list[str] = []
    failures: list[str] = []

    def build_user_msg(section: dict) -> str:
        indexes, used_all = _routed_evidence(selected, section["chunk_types"])
        coverage.append(
            f"- {section['number']}. {section['title']}: "
            + ("all selected evidence" if used_all else ", ".join(section["chunk_types"]))
            + f" ({len(indexes)} chunk(s))"
        )
        blocks = "\n\n".join(_evidence_block(i, selected[i - 1], section["cap"]) for i in indexes)
        return (_header(report_request, classification) + _section_rules(section["number"], section["title"])
                + "\nEVIDENCE:\n" + blocks)

    def run_section(section: dict, user_msg: str) -> tuple[Optional[str], Optional[str]]:
        try:
            body = _strip_own_heading(
                llm_chat([{"role": "system", "content": REPORT_SYSTEM_PROMPT},
                          {"role": "user", "content": user_msg}]).strip(), section["number"])
            return body, None
        except Exception as exc:
            return None, f"- Section {section['number']}. {section['title']} could not be generated: {exc}"

    with ThreadPoolExecutor(max_workers=min(_SECTION_WORKERS, len(_SECTIONS))) as pool:
        futures = [(section, pool.submit(run_section, section, build_user_msg(section)))
                   for section in _SECTIONS]
        for section, future in futures:
            body, failure = future.result()
            if failure:
                failures.append(failure)
                continue
            parts.append(f"## {section['number']}. {section['title']}\n\n{body}".rstrip() + "\n")
            if progress:
                progress("report_section", {"number": section["number"], "title": section["title"],
                                            "index": len(parts) - 1})

    gaps_msg = (
        _header(report_request, classification)
        + "SECTION COVERAGE OF THE DRAFTED REPORT (evidence routed per section):\n"
        + "\n".join(coverage) + "\n\n"
        + _section_rules(_GAPS_SECTION["number"], _GAPS_SECTION["title"])
        + "- List the agent's known gaps, anything the section coverage above shows was missing, "
          "and the items a human reviewer must verify before use.\n"
        + ("- Generation notes to include:\n" + "\n".join(failures) + "\n" if failures else "")
        + "\nNo evidence blocks are attached: this section reports what is missing, not tested facts."
    )
    baseline_gaps = [f"- Known gap from the agent: {g}"
                     for g in classification.get("known_evidence_gaps", [])]
    try:
        gaps_body = _strip_own_heading(
            llm_chat([{"role": "system", "content": REPORT_SYSTEM_PROMPT},
                      {"role": "user", "content": gaps_msg}]).strip(), _GAPS_SECTION["number"])
    except Exception as exc:
        gaps_body = ""
        baseline_gaps.append(f"- Evidence-gap review could not be generated: {exc}")
    parts.append(f"## {_GAPS_SECTION['number']}. {_GAPS_SECTION['title']}\n\n{gaps_body}".rstrip() + "\n")
    parts.append("\n".join(failures + baseline_gaps) + "\n" if failures + baseline_gaps else "")

    parts.append(f"## 7. Disclaimer\n\n{DISCLAIMER_TEXT}\n")
    report = "\n".join(parts)

    output_file = Path(output_file)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(report, encoding="utf-8")
    return report, str(output_file.resolve())
